"""Generates smoke/run-real-host.ts from the extension's own smoke test (extension/tests/smoke/run.ts, read only), by a list of exact text
replacements. Each replacement must match exactly once: if the extension's test changes, this fails loudly instead of testing something else.

    python -I smoke/make-real-host-smoke.py
"""
import pathlib

here = pathlib.Path(__file__).resolve().parent
src = (here.parent.parent.parent / "extension" / "tests" / "smoke" / "run.ts").read_text(encoding="utf8")

edits = []


def sub(old, new, count=1):
    edits.append((old, new, count))


# ---- header, imports, paths ------------------------------------------------------------------------------------------------------
sub(
    "// Headless Chromium smoke test of the extension against a MOCK native host.\n//   bun scripts/build.ts --test && bun tests/smoke/run.ts\n",
    "// GENERATED by smoke/make-real-host-smoke.py from extension/tests/smoke/run.ts. Do not edit by hand.\n"
    "// Headless Chromium smoke test of the extension against the REAL kin-native-host.exe (dev build) and the mock-kin stand-in on the pipe.\n"
    "//   cargo build --features dev,mock --bins --target-dir target/dev   (in desktop/native-host)\n"
    "//   bun smoke/run-real-host.ts                                       (the extension's dist/chromium-test must be built: bun scripts/build.ts --test)\n",
)
sub('from "playwright-core";', 'from "../../../extension/node_modules/playwright-core";')
sub(
    'const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");\nconst extDir = join(root, "dist", "chromium-test");\nconst shotsDir = resolve(root, "../docs/results/phase-2b-1-extension-screens");',
    'const here = resolve(dirname(fileURLToPath(import.meta.url)));\nconst hostRoot = resolve(here, "..");\nconst extRoot = resolve(here, "../../../extension");\n'
    'const extDir = join(extRoot, "dist", "chromium-test");\nconst shotsDir = join(tmpdir(), `kin-real-host-shots-${process.pid}`);\n'
    'const HOST_EXE = join(hostRoot, "target", "dev", "debug", "kin-native-host.exe");\nconst KIN_EXE = join(hostRoot, "target", "dev", "debug", "mock-kin.exe");',
)

# ---- the mock host is replaced by the real host + mock-kin ----------------------------------------------------------------------
sub(
    '  // The mock host and its wrapper. Browsers start a .cmd on Windows through cmd.exe.\n'
    '  const mock = join(root, "tests", "smoke", "mock-host.ts");\n'
    '  const cmdPath = join(hostDir, "mock-host.cmd");\n'
    '  writeFileSync(cmdPath, `@echo off\\r\\n"${process.execPath}" "${mock}" --state "${state}" %*\\r\\n`);\n',
    '  // The real host (dev build), with a dev environment: a pipe of its own (never the release pipe),\n'
    '  // the mock-kin as the Kin to start, and where the mock-kin keeps its state.\n'
    '  check(existsSync(HOST_EXE) && existsSync(KIN_EXE), `build the dev host first: cargo build --features dev,mock --bins --target-dir target/dev (${HOST_EXE})`);\n'
    '  const sid = spawnSync("powershell", ["-NoProfile", "-Command", "[Security.Principal.WindowsIdentity]::GetCurrent().User.Value"], { encoding: "utf8" }).stdout.trim();\n'
    '  check(/^S-1-5-/.test(sid), "could not read the user SID");\n'
    '  const PIPE = `\\\\\\\\.\\\\pipe\\\\kin-host-test-smoke-${process.pid}`;\n'
    "  // No wrapper: the manifest's path is the host exe itself, exactly as in production. Its environment is the browser's, set at launch.\n"
    "  const cmdPath = HOST_EXE;\n"
    "  const hostEnv = { KIN_HOST_DEV_PIPE: PIPE, KIN_HOST_DEV_KIN_EXE: KIN_EXE, KIN_MOCK_PIPE: PIPE, KIN_MOCK_STATE: state };\n",
)
sub('description: "Kin mock host (test)"', 'description: "Kin real host (smoke test)"')

sub(
    "      headless: true, // never a visible window\n",
    "      headless: true, // never a visible window\n      env: { ...(process.env as Record<string, string>), ...hostEnv },\n",
)

# scenario control: "running" is a real process now
sub(
    '  const setScenario = (s: Record<string, unknown>) => writeFileSync(join(state, "scenario.json"), JSON.stringify(s));\n',
    '''  // ---- Kin (the mock-kin process) -------------------------------------------------------------------------------------------------
  const startsLog = join(state, "starts.log");
  const startedPids = () => (existsSync(startsLog) ? readFileSync(startsLog, "utf8").split("\\n").filter(Boolean).map(Number) : []);
  const starts = () => startedPids().length;
  const killKin = () => {
    // Only mock-kin processes whose pids are in OUR state folder (image-checked, so a reused pid is never killed).
    for (const pid of startedPids()) spawnSync("taskkill", ["/PID", String(pid), "/F", "/FI", "IMAGENAME eq mock-kin.exe"], { encoding: "utf8" });
  };
  const kinUp = () => {
    const f = join(state, "kin.pid");
    if (!existsSync(f)) return false;
    const pid = readFileSync(f, "utf8").trim();
    return spawnSync("tasklist", ["/FI", `PID eq ${pid}`, "/FI", "IMAGENAME eq mock-kin.exe", "/NH"], { encoding: "utf8" }).stdout.includes("mock-kin.exe");
  };
  const waitKin = async (up: boolean) => {
    for (let i = 0; i < 100; i++) {
      if (kinUp() === up) return;
      await new Promise((r) => setTimeout(r, 100));
    }
    throw new Error(`mock-kin did not become ${up ? "up" : "down"}`);
  };
  /** The extension test's scenarios: \\`running\\` is a real process here (started by hand with --manual, or stopped), the rest is the mock-kin's scenario file. */
  const setScenario = async (s: Record<string, unknown>) => {
    const { running, ...rest } = s as { running?: boolean };
    writeFileSync(join(state, "scenario.json"), JSON.stringify(rest));
    if (running === false) {
      killKin();
      rmSync(join(state, "kin.pid"), { force: true });
      await new Promise((r) => setTimeout(r, 300));
    } else if (!kinUp()) {
      const child = spawn(KIN_EXE, ["--pipe", PIPE, "--state", state, "--manual"], { detached: true, stdio: "ignore", windowsHide: true });
      child.unref();
      await waitKin(true);
      await new Promise((r) => setTimeout(r, 200));
    }
  };
''',
)
sub('import { spawnSync } from "node:child_process";', 'import { spawn, spawnSync } from "node:child_process";')

# the scenarios are now async
sub("    setScenario(scenarioTwo);\n    resetLog();\n", "    await setScenario(scenarioTwo);\n    resetLog();\n")
sub("      setScenario(scenarioOne);\n      await kin(\"refreshStatus\");", "      await setScenario(scenarioOne);\n      await kin(\"refreshStatus\");")
sub("      setScenario({ running: false, startable: true, devices: [] });\n      const p = await ctx.newPage();", "      await setScenario({ running: false, startable: true, devices: [] });\n      const startsBefore = starts();\n      const p = await ctx.newPage();")
sub(
    '      setScenario({ ...scenarioOne, running: false, startable: true });\n      await p.locator("#start").click();',
    '      eq(starts(), startsBefore, "opening the popup (status) must not start Kin");\n      await setScenario({ ...scenarioOne, running: false, startable: true });\n      await p.locator("#start").click();',
)
sub('      eq(requests("start").length >= 1, true, "host got start");\n', '      eq(requests("start").length >= 1, true, "Kin got start");\n      eq(starts(), startsBefore + 1, "the host started Kin exactly once");\n      check(kinUp(), "the Kin the host started is serving");\n')
sub('      setScenario({ running: false, startable: false, devices: [] });\n      const out = await click({ menuItemId: "kin:send", selectionText: "x" }, tab);', '      await setScenario({ running: false, startable: false, devices: [] });\n      const out = await click({ menuItemId: "kin:send", selectionText: "x" }, tab);')
sub('      setScenario({ running: true, startable: true, devices: [] });\n      const p = await ctx.newPage();', '      await setScenario({ running: true, startable: true, devices: [] });\n      const p = await ctx.newPage();')
sub('      setScenario({ ...scenarioOne, exitWithoutAnswer: true });', '      await setScenario({ ...scenarioOne, exitWithoutAnswer: true });')
sub('      setScenario({ ...scenarioOne, badRef: true });', '      await setScenario({ ...scenarioOne, badRef: true });')
sub('      setScenario({ ...scenarioOne, sendError: { code: "TOO_LARGE", message: "Kin says: too big." } });', '      await setScenario({ ...scenarioOne, sendError: { code: "TOO_LARGE", message: "Kin says: too big." } });')

# ---- what differs with the real host ----------------------------------------------------------------------------------------------
sub('eq(sends[0].origin === undefined, true, "extension doesn\'t invent an origin");', 'eq(sends[0].origin, `chrome-extension://${EXPECTED_ID}/`, "the host adds the browser\'s origin");\n      check(typeof sends[0].hostVersion === "string", "the host adds its version");')
sub(
    'await step("a host that exits without answering: HOST_EXITED", async () => {',
    'await step("Kin hangs up without answering: the host answers INTERNAL (the real host does not exit)", async () => {',
)
sub('eq([out.outcome, out.code], ["failed", "HOST_EXITED"], "outcome");', 'eq([out.outcome, out.code], ["failed", "INTERNAL"], "outcome");')

# ---- cleanup --------------------------------------------------------------------------------------------------------------------
sub(
    "    site.stop(true);\n    unregister();",
    "    site.stop(true);\n    unregister();\n    killKin();",
)
sub("    rmSync(work, { recursive: true, force: true });", "    rmSync(work, { recursive: true, force: true });\n    rmSync(shotsDir, { recursive: true, force: true });")

# the dist/ build of the extension and the "mock host" wording in messages
sub("`${extDir} is not built. Run: bun scripts/build.ts --test`", "`${extDir} is not built. Run in extension/: bun scripts/build.ts --test`")

out = src
for old, new, count in edits:
    n = out.count(old)
    if n != count:
        raise SystemExit(f"replacement expected {count} match(es), found {n}:\n{old[:200]}")
    out = out.replace(old, new)

(here / "run-real-host.ts").write_text(out, encoding="utf8")
print(f"wrote {here / 'run-real-host.ts'} ({len(edits)} replacements)")
